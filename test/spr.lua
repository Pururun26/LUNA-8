function luna()
    cls(0)

    -- 4 варианта flip
    spr(1,  20, 20)                 -- обычный
    spr(1,  40, 20, true)           -- зеркало по X
    spr(1,  60, 20, false, true)    -- зеркало по Y
    spr(1,  80, 20, true, true)     -- оба

    -- фон: вертикальные полосы, чтобы видеть прозрачность
    for i = 0, 159, 8 do
        line(i, 0, i, 89, 1)
    end

    -- без colorkey — ромб перекрывает полосы (0-пиксели рисуются)
    spr(2,  20, 50)
    -- с colorkey=0 — полосы видны сквозь 0-пиксели
    spr(2,  60, 50, false, false, 0)
    -- и ещё один, сдвинутый и перевёрнутый
    spr(2, 100, 50, true, false, 0)

    text("FLIP X / Y / BOTH", 5, 5, 5)
    text("COLORKEY 0", 5, 80, 5)
end